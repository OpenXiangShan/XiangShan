/** Code points that the "C" / "Zc" manuals mark as reserved. Used by the illegal-instruction
  * table of [[RVCDecoder]]; each entry quotes the validity rule that makes the code point
  * reserved.
  */
object RVCReserved {

  /** C.ADDI4SPN is valid only when nzuimm != 0 (inst[12:5] != 0). */
  def C_ADDI4SPN: BitPat = BitPat("b????????????????00000000000???00")

  /** C.ADDIW (RV64) is valid only when rd != x0. */
  def C_ADDIW: BitPat = BitPat("b????????????????001?00000?????01")

  /** C.LWSP is valid only when rd != x0. */
  def C_LWSP: BitPat = BitPat("b????????????????010?00000?????10")

  /** C.LDSP (RV64) is valid only when rd != x0. */
  def C_LDSP: BitPat = BitPat("b????????????????011?00000?????10")

  /** C.LUI / C.ADDI16SP are valid only when nzimm != 0 (inst[12] = 0 and inst[6:2] = 0). */
  def C_LUI: BitPat = BitPat("b????????????????0110?????0000001")

  /** C.JR is valid only when rs1 != x0; the code point c.jr x0 is reserved. */
  def C_JR: BitPat = BitPat("b????????????????1000000000000010")

  /** Zcb unary-op group (funct6 = 100111, inst[6:5] = 11), selector inst[4:2] = 110 is reserved. */
  def ZCB_UNIMP0: BitPat = BitPat("b????????????????100111???1111001")

  /** Zcb unary-op group, selector inst[4:2] = 111 is reserved. */
  def ZCB_UNIMP1: BitPat = BitPat("b????????????????100111???1111101")
}

/** A subset of compressed instructions, mirroring `Instructions.InstType` of the backend decoder. */
trait RVCInstType {

  /** all instructions of this format, as (pattern, name) pairs */
  val allWithNames: Seq[(BitPat, String)]

  def all: Seq[BitPat] = allWithNames.map(_._1)
}

/** CR: c.mv, c.jr, c.add, c.jalr, c.ebreak (two full registers). */
object CRType extends RVCInstType {
  val allWithNames: Seq[(BitPat, String)] = Seq(
    RVCInstructions.C_MV     -> "C.MV",
    RVCInstructions.C_JR     -> "C.JR",
    RVCInstructions.C_ADD    -> "C.ADD",
    RVCInstructions.C_JALR   -> "C.JALR",
    RVCInstructions.C_EBREAK -> "C.EBREAK"
  )
}

/** CI: a single register plus an immediate, including the stack-relative loads. */
object CIType extends RVCInstType {
  val allWithNames: Seq[(BitPat, String)] = Seq(
    RVCInstructions.C_ADDI     -> "C.ADDI",
    RVCInstructions.C_NOP      -> "C.NOP",
    RVCInstructions.C_ADDIW    -> "C.ADDIW", // RV64
    RVCInstructions.C_LI       -> "C.LI",
    RVCInstructions.C_LUI      -> "C.LUI",
    RVCInstructions.C_ADDI16SP -> "C.ADDI16SP",
    RVCInstructions.C_MOP_N    -> "C.MOP.N",
    RVCInstructions.C_SLLI     -> "C.SLLI",
    RVCInstructions.C_LWSP     -> "C.LWSP",
    RVCInstructions.C_LDSP     -> "C.LDSP",  // RV64
    RVCInstructions.C_FLDSP    -> "C.FLDSP",
    RVCInstructions.C_FLWSP    -> "C.FLWSP"  // RV32
  )
}

/** CSS: stack-relative stores. */

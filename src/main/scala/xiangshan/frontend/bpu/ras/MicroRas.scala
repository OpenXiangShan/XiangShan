package xiangshan.frontend.bpu.ras

import chisel3._
import chisel3.util._
import org.chipsalliance.cde.config.Parameters
import utility.HasCircularQueuePtrHelper
import utility.XSError
import utility.XSPerfAccumulate
import xiangshan.frontend.GuardedPc
import xiangshan.frontend.bpu.BasePredictor
import xiangshan.frontend.bpu.BasePredictorIO
import xiangshan.frontend.bpu.BranchAttribute
import xiangshan.frontend.bpu.HalfAlignHelper
import xiangshan.frontend.bpu.StageCtrl

/**
 * A speculative micro Return Address Stack (micro-RAS) used in the branch predictor.
 *
 * This module tracks pending call/return operations in the S1–S3 pipeline stages
 * and predicts the return target for upcoming RET instructions by modeling
 * the effect of in-flight push/pop operations on the main RAS.
 *
 * It outputs a predicted return address and a validity flag indicating whether
 * the prediction can be trusted in the current cycle.
 */
class MicroRas(implicit p: Parameters) extends BasePredictor with HasRasParameters with HalfAlignHelper {
  class MicroRasIO(implicit p: Parameters) extends BasePredictorIO {

    /** Input bundle containing speculative CFI (Control Flow Instruction) info from S1 */
    class MicroRasSpecIn extends Bundle {
      val startPc:     GuardedPc       = GuardedPc()
      val cfiPosition: UInt            = UInt(CfiPositionWidth.W)
      val attribute:   BranchAttribute = new BranchAttribute
    }

    /** Output bundle providing predicted return target and validity */
    class MicroRasSpecOut extends Bundle {
      val retTarget: GuardedPc = GuardedPc() // Predicted return address
      val isCanUse:  Bool      = Bool()      // Whether the prediction is valid
    }
    val specIn:         MicroRasSpecIn        = Input(new MicroRasSpecIn)
    val specOut:        MicroRasSpecOut       = Output(new MicroRasSpecOut)
    val hasRedirect:    Bool                  = Input(Bool())      // Global redirect signal (e.g., misprediction)
    val s2OverrideData: Valid[MicroRasSpecIn] = Input(Valid(new MicroRasSpecIn))
    val s3OverrideData: Valid[MicroRasSpecIn] = Input(Valid(new MicroRasSpecIn))
    val fullRetAddr:    GuardedPc             = Input(GuardedPc()) // Current top of the main RAS
  }
  val io = IO(new MicroRasIO)
  io.sramResetDone := true.B
  io.trainReady    := true.B

  // Track whether S2/S3 stages contain pending push/pop operations
  private val s2_hasPush = RegInit(false.B)
  private val s2_hasPop  = RegInit(false.B)
  private val s3_hasPush = RegInit(false.B)
  private val s3_hasPop  = RegInit(false.B)

  // Store return addresses generated by speculative pushes
  private val stackAddr     = RegInit(VecInit(Seq.fill(MicroRasDepth)(0.U.asTypeOf(GuardedPc()))))
  private val stackWriteIdx = RegInit(MicroRasPtr(false.B, 0.U))
  private val specCount     = RegInit(0.U(log2Ceil(MicroRasDepth + 1).W))

  private def incSpecCount(count: UInt): UInt =
    Mux(count === MicroRasDepth.U, count, count + 1.U)
  private def decSpecCount(count: UInt): UInt =
    Mux(count === 0.U, count, count - 1.U)

  // State before the youngest speculative operation.
  private val youngestRestoreAddr     = RegInit(0.U.asTypeOf(GuardedPc()))
  private val youngestRestoreWriteIdx = RegInit(MicroRasPtr(false.B, 0.U))
  private val youngestRestoreCount    = RegInit(0.U(log2Ceil(MicroRasDepth + 1).W))

  // State before the next older speculative operation.
  private val olderRestoreAddr     = RegInit(0.U.asTypeOf(GuardedPc()))
  private val olderRestoreWriteIdx = RegInit(MicroRasPtr(false.B, 0.U))
  private val olderRestoreCount    = RegInit(0.U(log2Ceil(MicroRasDepth + 1).W))

  // Final output: whether a valid return target is available, and what its target is.
  private val isCanUse   = RegInit(false.B)
  private val topRetAddr = RegInit(0.U.asTypeOf(GuardedPc()))

  // Decode speculative operation from S1 input
  private val specPush = io.specIn.attribute.isCall
  private val specPop  = io.specIn.attribute.isReturn
  // Compute return address for a CALL
  private val specPushAddr = getCfiPcFromPosition(io.specIn.startPc, io.specIn.cfiPosition) + 2.U

  // One-cycle delayed version of redirect; used to detect RAS recovery state
  private val redirectDelay1 = RegNext(io.hasRedirect, init = false.B)

  private val s2_override = io.s2OverrideData.valid
  private val s2_realPush = io.s2OverrideData.bits.attribute.isCall
  private val s2_realPop  = io.s2OverrideData.bits.attribute.isReturn
  private val s2_realPushAddr =
    getCfiPcFromPosition(io.s2OverrideData.bits.startPc, io.s2OverrideData.bits.cfiPosition) + 2.U

  private val s3_override = io.s3OverrideData.valid
  private val s3_realPush = io.s3OverrideData.bits.attribute.isCall
  private val s3_realPop  = io.s3OverrideData.bits.attribute.isReturn
  private val s3_realPushAddr =
    getCfiPcFromPosition(io.s3OverrideData.bits.startPc, io.s3OverrideData.bits.cfiPosition) + 2.U

  // Pipeline operation bookkeeping.
  when(s3_override || io.hasRedirect) {
    s2_hasPush := false.B
    s2_hasPop  := false.B
  }.elsewhen(s2_override) {
    s2_hasPush := Mux(io.stageCtrl.s2_fire, false.B, s2_realPush)
    s2_hasPop  := Mux(io.stageCtrl.s2_fire, false.B, s2_realPop)
  }.elsewhen(io.stageCtrl.s1_fire) {
    s2_hasPush := specPush
    s2_hasPop  := specPop
  }.elsewhen(io.stageCtrl.s2_fire) {
    s2_hasPush := false.B
    s2_hasPop  := false.B
  }

  when(s3_override || io.hasRedirect) {
    s3_hasPush := false.B
    s3_hasPop  := false.B
  }.elsewhen(io.stageCtrl.s2_fire) {
    s3_hasPush := Mux(s2_override, s2_realPush, s2_hasPush)
    s3_hasPop  := Mux(s2_override, s2_realPop, s2_hasPop)
  }.elsewhen(io.stageCtrl.s3_fire) {
    s3_hasPush := false.B
    s3_hasPop  := false.B
  }

  when(io.stageCtrl.s1_fire && !s2_override && !s3_override && !io.hasRedirect) {
    youngestRestoreAddr     := stackAddr(stackWriteIdx.value)
    youngestRestoreWriteIdx := stackWriteIdx
    youngestRestoreCount    := specCount
  }

  when(io.stageCtrl.s2_fire && !s3_override && !io.hasRedirect) {
    olderRestoreAddr     := youngestRestoreAddr
    olderRestoreWriteIdx := youngestRestoreWriteIdx
    olderRestoreCount    := youngestRestoreCount
  }

  // Default output state is conservative.  In particular, never retain a
  // previous valid prediction after a pop whose resulting top is unknown.
  when(io.hasRedirect) {
    isCanUse      := false.B
    topRetAddr    := 0.U.asTypeOf(GuardedPc())
    stackWriteIdx := MicroRasPtr(false.B, 0.U)
    specCount     := 0.U
  }.elsewhen(s3_override) {
    // Restore both slots that may have been overwritten by S1/S2 pushes.
    stackAddr(youngestRestoreWriteIdx.value) := youngestRestoreAddr
    stackAddr(olderRestoreWriteIdx.value)    := olderRestoreAddr
    stackWriteIdx                            := olderRestoreWriteIdx
    specCount                                := olderRestoreCount
    isCanUse                                 := false.B
    topRetAddr                               := 0.U.asTypeOf(GuardedPc())

    when(s3_realPush) {
      stackAddr(olderRestoreWriteIdx.value) := s3_realPushAddr
      stackWriteIdx                         := olderRestoreWriteIdx + 1.U
      specCount                             := incSpecCount(olderRestoreCount)
      isCanUse                              := true.B
      topRetAddr                            := s3_realPushAddr
    }.elsewhen(s3_realPop) {
      stackWriteIdx := olderRestoreWriteIdx - 1.U
      specCount     := decSpecCount(olderRestoreCount)
      when(olderRestoreCount > 1.U) {
        isCanUse   := true.B
        topRetAddr := stackAddr((olderRestoreWriteIdx - 2.U).value)
      }
    }.otherwise {
      isCanUse   := true.B
      topRetAddr := io.fullRetAddr
    }
  }.elsewhen(s2_override) {
    stackAddr(youngestRestoreWriteIdx.value) := youngestRestoreAddr
    stackWriteIdx                            := youngestRestoreWriteIdx
    specCount                                := youngestRestoreCount
    isCanUse                                 := false.B
    topRetAddr                               := 0.U.asTypeOf(GuardedPc())

    when(s2_realPush) {
      stackAddr(youngestRestoreWriteIdx.value) := s2_realPushAddr
      stackWriteIdx                            := youngestRestoreWriteIdx + 1.U
      specCount                                := incSpecCount(youngestRestoreCount)
      isCanUse                                 := true.B
      topRetAddr                               := s2_realPushAddr
    }.elsewhen(s2_realPop) {
      stackWriteIdx := youngestRestoreWriteIdx - 1.U
      specCount     := decSpecCount(youngestRestoreCount)
      when(youngestRestoreCount > 1.U) {
        isCanUse   := true.B
        topRetAddr := stackAddr((youngestRestoreWriteIdx - 2.U).value)
      }.elsewhen(youngestRestoreCount === 1.U && s3_hasPush) {
        // The older S3 push supplies a known top after this pop.
        isCanUse   := true.B
        topRetAddr := io.fullRetAddr
      }
    }.otherwise {
      when(youngestRestoreCount > 0.U) {
        isCanUse   := true.B
        topRetAddr := stackAddr((youngestRestoreWriteIdx - 1.U).value)
      }.elsewhen(!s3_hasPop) {
        isCanUse   := true.B
        topRetAddr := io.fullRetAddr
      }
    }
  }.elsewhen(io.stageCtrl.s1_fire) {
    isCanUse   := false.B
    topRetAddr := 0.U.asTypeOf(GuardedPc())

    when(specPush) {
      stackAddr(stackWriteIdx.value) := specPushAddr
      stackWriteIdx                  := stackWriteIdx + 1.U
      specCount                      := incSpecCount(specCount)
      isCanUse                       := true.B
      topRetAddr                     := specPushAddr
    }.elsewhen(specPop) {
      stackWriteIdx := stackWriteIdx - 1.U
      specCount     := decSpecCount(specCount)
      // fullRetAddr is the pre-pop main-RAS top.  It cannot be used as the
      // post-pop top.  Only another remaining micro entry is known exactly.
      when(specCount > 1.U) {
        isCanUse   := true.B
        topRetAddr := stackAddr((stackWriteIdx - 2.U).value)
      }
    }.otherwise {
      when(specCount =/= 0.U) {
        isCanUse   := true.B
        topRetAddr := stackAddr((stackWriteIdx - 1.U).value)
      }.elsewhen(s2_hasPop && s3_hasPush) {
        isCanUse   := true.B
        topRetAddr := io.fullRetAddr
      }.otherwise {
        isCanUse   := Mux(redirectDelay1 || s2_hasPop || s3_hasPop, false.B, true.B)
        topRetAddr := Mux(redirectDelay1 || s2_hasPop || s3_hasPop, 0.U.asTypeOf(GuardedPc()), io.fullRetAddr)
      }
    }
  }

  io.specOut.isCanUse  := isCanUse
  io.specOut.retTarget := topRetAddr

  private val s2_canUseRas   = RegEnable(isCanUse, io.stageCtrl.s1_fire)
  private val s3_canUseRas   = RegEnable(s2_canUseRas, io.stageCtrl.s2_fire)
  private val s2_predictAddr = RegEnable(topRetAddr, io.stageCtrl.s1_fire)
  private val s3_predictAddr = RegEnable(s2_predictAddr, io.stageCtrl.s2_fire)
  private val targetDiff     = s3_predictAddr =/= io.fullRetAddr

  XSPerfAccumulate(
    "microRas_mispredict",
    s3_canUseRas && s3_override && s3_realPop && io.stageCtrl.s3_fire && targetDiff
  )
  XSPerfAccumulate(
    "microRas_mispredict_not_excepted",
    s3_canUseRas && s3_override && s3_realPop && io.stageCtrl.s3_fire
  )
  XSPerfAccumulate(
    "microRas_predict",
    s3_canUseRas && s3_realPop && io.stageCtrl.s3_fire
  )
  XSPerfAccumulate(
    "microRas_need_predict",
    s3_hasPop && s3_realPop && io.stageCtrl.s3_fire
  )
  XSPerfAccumulate(
    "microRas_need_predict_and_mispredict",
    s3_hasPop && s3_realPop && s3_override && io.stageCtrl.s3_fire && targetDiff
  )
  XSPerfAccumulate(
    "microRas_need_predict_and_mispredict_not_excepted",
    s3_hasPop && s3_realPop && s3_override && io.stageCtrl.s3_fire
  )
  XSPerfAccumulate(
    "mainRas_actual_ret",
    s3_realPop && io.stageCtrl.s3_fire
  )
}
